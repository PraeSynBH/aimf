#!/usr/bin/env python3
"""AIMF assessment question-bank generator and validator.

Why this file exists
--------------------
The bank is the thing a buyer pays for.  Two copies of it are shipped - the
full instrument (``implementation/AIMF-ASSESSMENT-QUESTION-BANK.md``) and the
compact question tables inside the Assessment Guide - and both carry coverage
counts.  Hand-maintained copies drift, so both are rendered here from:

* ``core/AIMF-CONTROL-CATALOG.csv`` - the control set (72 rows), the control
  dimension that decides the audience, and the function grouping;
* ``implementation/AIMF-ASSESSMENT-QUESTION-BANK.csv`` - the authored content:
  question, evidence expectation, role asked, and the five behavioural anchors
  (0-4 / ML1-ML5) per control.

The audience is *derived*, never authored per question: the catalog dimension
decides it (D1 Leadership, D2 Governance, D3 Technical, D4 Change Agent), with
a short, reasoned override table for controls whose evidence is owned by a
different audience than their dimension implies.

Usage
-----
    python3 scripts/aimf_question_bank.py generate   # rewrite both documents
    python3 scripts/aimf_question_bank.py check      # validate only (exit 1)
    python3 scripts/aimf_question_bank.py report     # coverage counts

Works from the repository copy of the packaged directory and from an unpacked
distribution bundle (same layout detection as ``aimf_mappings.py``).
"""

from __future__ import annotations

import argparse
import csv
import re
import sys
from collections import OrderedDict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import aimf_mappings as am  # noqa: E402  (DOCS, catalog loader, markdown helpers)

DOCS = am.DOCS
SOURCE = DOCS / "implementation" / "AIMF-ASSESSMENT-QUESTION-BANK.csv"
BANK_MD = DOCS / "implementation" / "AIMF-ASSESSMENT-QUESTION-BANK.md"
GUIDE_MD = am.QUESTION_BANK_MD

FIELDS = ["control", "question", "evidence", "role",
          "anchor_0", "anchor_1", "anchor_2", "anchor_3", "anchor_4"]
ANCHORS = ["anchor_0", "anchor_1", "anchor_2", "anchor_3", "anchor_4"]

# --- the audience model (implementation/AIMF-ASSESSMENT-GUIDE.md) -----------
AUDIENCE_BY_DIMENSION = OrderedDict([
    ("D1", "Leadership"),
    ("D2", "Governance"),
    ("D3", "Technical"),
    ("D4", "Change Agent"),
])
AUDIENCE_ORDER = ["Leadership", "Technical", "Governance", "Change Agent"]
AUDIENCE_PRIMARY_DIMENSION: OrderedDict[str, str] = OrderedDict([
    ("Leadership", "D1"),
    ("Technical", "D3"),
    ("Governance", "D2"),
    ("Change Agent", "D4"),
])

# Controls whose primary evidence is owned by an audience other than the one
# their catalog dimension implies.  Each entry says why; the override is what
# keeps the derivation auditable rather than arbitrary.
AUDIENCE_OVERRIDES = OrderedDict([
    ("GOV-1.4", ("Governance",
                 "compliance monitoring is executed and recorded by compliance, "
                 "not by the executive sponsor who owns the policy")),
    ("MAP-1.5", ("Governance",
                 "the deliverable is an approved risk-tolerance statement, a "
                 "governance record signed by the risk function")),
    ("MEA-1.3", ("Governance",
                 "independent evaluation is commissioned and recorded by audit "
                 "or compliance, not by the build team")),
    ("MAN-4.3", ("Governance",
                 "communicating incidents to stakeholders is a compliance "
                 "reporting duty with a record obligation")),
])

# The canonical scale.  Kept here so the document's scale table is generated
# from the same place the anchors are checked against.
SCALE = OrderedDict([
    (0, ("ML1 - Initial",
         "Capability absent or undocumented; holds only in individuals' heads.",
         "The artefact does not exist and the answer is a description of intent.")),
    (1, ("ML2 - Developing",
         "Documented but inconsistent; partial coverage.",
         "The artefact exists but is partial, unapproved, stale, or applied to some teams or systems only.")),
    (2, ("ML3 - Defined",
         "Documented, approved, applied organization-wide and audited.",
         "The artefact exists, is current and approved, and covers every in-scope AI system.")),
    (3, ("ML4 - Managed",
         "ML3 plus quantitative measures reviewed against targets and used in decisions.",
         "The level-2 evidence plus a measured indicator of whether the control works, reviewed on a cadence.")),
    (4, ("ML5 - Optimizing",
         "ML4 plus systematic, repeated improvement driven by that measurement.",
         "The level-3 evidence plus a documented change traceable to the measurement, repeated over at least two review cycles.")),
])

GEN_NOTE = ("<!-- GENERATED by scripts/aimf_question_bank.py from "
            "core/AIMF-CONTROL-CATALOG.csv + "
            "implementation/AIMF-ASSESSMENT-QUESTION-BANK.csv - do not edit by hand -->")

ANCHOR3_PREFIX = "Level 2 evidence plus"
ANCHOR4_PREFIX = "Level 3 evidence plus"
OLD_SCALE_RE = re.compile(r"\b0\s*[-\u2013]\s*3\b|four[-\s]level", re.IGNORECASE)


# ---------------------------------------------------------------------------
# data
# ---------------------------------------------------------------------------
def load_source() -> tuple[list[dict], list[str]]:
    """Return the authored rows and any structural problems in the source file."""
    problems = []
    if not SOURCE.is_file():
        return [], [f"{SOURCE.name}: authored source not found"]
    with SOURCE.open(newline="", encoding="utf-8") as fh:
        reader = csv.DictReader(fh)
        header = reader.fieldnames or []
        if header != FIELDS:
            problems.append(f"{SOURCE.name}: header is {header}, expected {FIELDS}")
        rows = list(reader)
    return rows, problems


def audience_for(control_row: dict) -> tuple[str, str]:
    """Derive the audience for a catalog control, with its derivation note."""
    cid = control_row["Control_ID"]
    if cid in AUDIENCE_OVERRIDES:
        audience, reason = AUDIENCE_OVERRIDES[cid]
        return audience, f"override ({control_row['Dimension']} would be {AUDIENCE_BY_DIMENSION[control_row['Dimension']]}): {reason}"
    dim = control_row["Dimension"]
    return AUDIENCE_BY_DIMENSION[dim], f"catalog Dimension {dim}"


def records() -> tuple[list[dict], list[str]]:
    """Join the authored rows to the catalog in catalog order."""
    catalog = am.load_catalog()
    source, problems = load_source()
    by_id = {r.get("control", "").strip(): r for r in source}
    out = []
    for row in catalog:
        cid = row["Control_ID"]
        authored = by_id.get(cid)
        if authored is None:
            continue
        audience, note = audience_for(row)
        rec = {k: (authored.get(k) or "").strip() for k in FIELDS}
        rec["control"] = cid
        rec["function"] = row["Function"]
        rec["dimension"] = row["Dimension"]
        rec["name"] = row["Control_Name"]
        rec["audience"] = audience
        rec["derivation"] = note
        out.append(rec)
    return out, problems


# ---------------------------------------------------------------------------
# renderers
# ---------------------------------------------------------------------------
def render_scale() -> str:
    return am.md_table(
        ["Score", "Maturity level", "What the level means", "What the answer must show"],
        [[str(score), level, meaning, proof] for score, (level, meaning, proof) in SCALE.items()])


def render_derivation(recs: list[dict]) -> str:
    rule = am.md_table(
        ["Catalog dimension", "Audience", "Controls"],
        [[f"{AUDIENCE_PRIMARY_DIMENSION[a]}: {a}", a,
          str(sum(1 for r in recs if r["audience"] == a))]
         for a in AUDIENCE_ORDER])
    overrides = am.md_table(
        ["Audience", "Catalog dimension", "Control", "Why the audience differs"],
        [[audience, next((r["dimension"] for r in recs if r["control"] == cid), ""), cid, reason]
         for cid, (audience, reason) in AUDIENCE_OVERRIDES.items()])
    return ("**Default rule.** The audience is the catalog `Dimension` of the control, read through the\n"
            "four-audience model in `AIMF-ASSESSMENT-GUIDE.md` (Leadership D1, Governance D2,\n"
            "Technical D3, Change Agent D4): the audience assessed is the one that has to produce the\n"
            "evidence, not the one that owns the risk.\n\n"
            + rule
            + "\n\n**Documented overrides.** Four controls sit with Governance because the artefact\n"
            "that answers them is a compliance or audit record. The override is part of the model,\n"
            "not a per-question judgement, and `scripts/aimf_question_bank.py check` derives the same\n"
            "audience for every row:\n\n"
            + overrides)


def render_tally(recs: list[dict], total: int) -> str:
    by_audience = OrderedDict((a, [r for r in recs if r["audience"] == a]) for a in AUDIENCE_ORDER)
    functions = ["GOVERN", "MAP", "MEASURE", "MANAGE"]
    rows = []
    for audience, subset in by_audience.items():
        row = [audience, str(len(subset))]
        row += [str(sum(1 for r in subset if r["function"] == f)) for f in functions]
        row.append(f"{100 * len(subset) / total:.0f}%")
        rows.append(row)
    rows.append(["**Total**", f"**{len(recs)}**"]
                + [f"**{sum(1 for r in recs if r['function'] == f)}**" for f in functions]
                + ["**100%**"])
    table = am.md_table(["Audience"] + ["Controls"] + [f[:4].title() for f in functions] + ["Share"], rows)
    verbatim = (f"**{len(recs)}/{total} controls.** Every `Control_ID` in "
                f"`core/AIMF-CONTROL-CATALOG.csv` appears in exactly one table below, once: "
                f"GOVERN {sum(1 for r in recs if r['function'] == 'GOVERN')}, "
                f"MAP {sum(1 for r in recs if r['function'] == 'MAP')}, "
                f"MEASURE {sum(1 for r in recs if r['function'] == 'MEASURE')}, "
                f"MANAGE {sum(1 for r in recs if r['function'] == 'MANAGE')}; "
                f"Leadership {len(by_audience['Leadership'])}, "
                f"Technical {len(by_audience['Technical'])}, "
                f"Governance {len(by_audience['Governance'])}, "
                f"Change Agent {len(by_audience['Change Agent'])}. "
                f"The counts on this page are generated from the catalog and the authored bank; "
                f"`check` fails if they disagree.")
    return verbatim + "\n\n" + table


def render_bank_tables(recs: list[dict], total: int) -> str:
    out = []
    for audience in AUDIENCE_ORDER:
        subset = [r for r in recs if r["audience"] == audience]
        dim = AUDIENCE_PRIMARY_DIMENSION[audience]
        out.append(f"### {audience} ({len(subset)} of {total} controls, primary dimension {dim})\n")
        out.append(am.md_table(
            ["Control", "Question", "Evidence", "Role", "Audience",
             "Anchor 0", "Anchor 1", "Anchor 2", "Anchor 3", "Anchor 4"],
            [[r["control"], r["question"], r["evidence"], r["role"], r["audience"]]
             + [r[a] for a in ANCHORS] for r in subset]))
        out.append("")
    return "\n".join(out)


def render_guide_tables(recs: list[dict], total: int) -> str:
    out = []
    for audience in AUDIENCE_ORDER:
        subset = [r for r in recs if r["audience"] == audience]
        out.append(f"#### {audience} Assessment ({len(subset)} of {total} controls)\n")
        out.append(am.md_table(
            ["Control", "Question", "Evidence to Look For", "Role asked"],
            [[r["control"], r["question"], r["evidence"], r["role"]] for r in subset]))
        out.append("")
    return "\n".join(out)


def render_guide_coverage(recs: list[dict], total: int) -> str:
    by_audience = OrderedDict((a, sum(1 for r in recs if r["audience"] == a)) for a in AUDIENCE_ORDER)
    return (
        f"**This bank covers {len(recs)}/{total} controls: one question, one evidence expectation and\n"
        f"one role for every `Control_ID` in `core/AIMF-CONTROL-CATALOG.csv`** (GOVERN "
        f"{sum(1 for r in recs if r['function'] == 'GOVERN')}, MAP "
        f"{sum(1 for r in recs if r['function'] == 'MAP')}, MEASURE "
        f"{sum(1 for r in recs if r['function'] == 'MEASURE')}, MANAGE "
        f"{sum(1 for r in recs if r['function'] == 'MANAGE')}: Leadership {by_audience['Leadership']},\n"
        f"Technical {by_audience['Technical']}, Governance {by_audience['Governance']}, Change Agent "
        f"{by_audience['Change Agent']}). Every catalog control appears in exactly one audience table\n"
        f"below, and `python3 scripts/aimf_mappings.py check` fails if the bank and the catalog\n"
        f"disagree on the control set - a control with no question, a control appearing twice, or an\n"
        f"ID that is not in the catalog.\n"
        f"\n"
        f"Questions are routed to the audience that has to produce the evidence: by default the\n"
        f"catalog's `Dimension` (`D1` Leadership, `D2` Governance, `D3` Technical, `D4` Change Agent).\n"
        f"Four controls whose primary evidence is a compliance or audit record sit with Governance\n"
        f"rather than their dimension's audience - `GOV-1.4`, `MAP-1.5`, `MEA-1.3` and `MAN-4.3` -\n"
        f"so the Governance table is short: the catalog attributes only two controls to `D2`\n"
        f"(`MAP-1.6`, `MEA-2.10`). The rule and the wording of each override are generated in\n"
        f"[AIMF-ASSESSMENT-QUESTION-BANK.md](AIMF-ASSESSMENT-QUESTION-BANK.md). An assessor may ask\n"
        f"any question of any audience provided the same evidence is scored.\n"
        f"\n"
        f"**How to score a question.** Ask it, then score 0-4 against what the interviewee can put on\n"
        f"the table in the session: nothing documented -> ML1 (0); a document exists -> ML2 (1);\n"
        f"documented and applied organization-wide -> ML3 (2); applied and measured -> ML4 (3);\n"
        f"measured and systematically improved -> ML5 (4). The evidence column names the artefacts\n"
        f"that carry a score above ML1, and the **per-control anchors** that fix what each of the\n"
        f"five answers looks like are in\n"
        f"[AIMF-ASSESSMENT-QUESTION-BANK.md](AIMF-ASSESSMENT-QUESTION-BANK.md) - score against the\n"
        f"anchor, not against recollection. Record the question asked, the artefact produced and the\n"
        f"score, so that a second assessor can reproduce the number. If the evidence cannot be\n"
        f"produced in the session, record the control as unresolved and re-book it; do not infer a\n"
        f"score from the interview alone.")


BLOCKS = OrderedDict([
    (BANK_MD, OrderedDict([
        ("bank-scale", lambda recs, total: render_scale()),
        ("bank-derivation", lambda recs, total: render_derivation(recs)),
        ("bank-tally", lambda recs, total: render_tally(recs, total)),
        ("bank-tables", lambda recs, total: render_bank_tables(recs, total)),
    ])),
    (GUIDE_MD, OrderedDict([
        ("assessment-guide-coverage", lambda recs, total: render_guide_coverage(recs, total)),
        ("assessment-guide-bank", lambda recs, total: render_guide_tables(recs, total)),
    ])),
])


def render(path: Path, recs: list[dict], total: int) -> tuple[str, list[str]]:
    text = path.read_text(encoding="utf-8")
    problems = []
    for block_id, fn in BLOCKS[path].items():
        pattern = am.block_pattern(block_id)
        if not pattern.search(text):
            problems.append(f"{path.name}: missing generated block '{block_id}'")
            continue
        body = GEN_NOTE + "\n" + am.wrap(block_id, fn(recs, total))
        text = pattern.sub(lambda _m, b=body: b, text)
    return text, problems


# ---------------------------------------------------------------------------
# validation
# ---------------------------------------------------------------------------
def validate(recs: list[dict], total: int, problems: list[str], check_files: bool = True) -> list[str]:
    errs = list(problems)
    catalog = am.load_catalog()
    ids = {r["Control_ID"] for r in catalog}
    have = {r["control"] for r in recs}

    for cid in sorted(ids - have):
        errs.append(f"{SOURCE.name}: no row for catalog control {cid}")
    for cid in sorted(have - ids):
        errs.append(f"{SOURCE.name}: row for unknown control {cid}")
    if len(recs) != len(ids):
        errs.append(f"{SOURCE.name}: {len(recs)} rows for {len(ids)} catalog controls")

    for r in recs:
        cid = r["control"]
        if not r["question"]:
            errs.append(f"{SOURCE.name}: {cid} has an empty question")
        elif not r["question"].endswith("?"):
            errs.append(f"{SOURCE.name}: {cid} question does not end with '?'")
        if not r["evidence"]:
            errs.append(f"{SOURCE.name}: {cid} has no evidence expectation")
        if not r["role"]:
            errs.append(f"{SOURCE.name}: {cid} has no role to ask")
        anchors = [r[a] for a in ANCHORS]
        for i, value in enumerate(anchors):
            if not value:
                errs.append(f"{SOURCE.name}: {cid} has an empty anchor {i}")
        if len(set(anchors)) != len(anchors):
            errs.append(f"{SOURCE.name}: {cid} repeats an anchor across levels")
        if not r["anchor_3"].startswith(ANCHOR3_PREFIX):
            errs.append(f"{SOURCE.name}: {cid} anchor 3 does not build on level 2 ('{ANCHOR3_PREFIX} ...')")
        if not r["anchor_4"].startswith(ANCHOR4_PREFIX):
            errs.append(f"{SOURCE.name}: {cid} anchor 4 does not build on level 3 ('{ANCHOR4_PREFIX} ...')")

    # no retired or invented scale may appear in the instrument
    bank_text = BANK_MD.read_text(encoding="utf-8") if BANK_MD.is_file() else ""
    for r in recs:
        for field_name, value in r.items():
            if field_name in ("question", "evidence", "role") or field_name in ANCHORS:
                if OLD_SCALE_RE.search(value):
                    errs.append(f"{SOURCE.name}: {r['control']} {field_name} asserts a non-0-4 scale")

    if not check_files:
        return errs

    for path in BLOCKS:
        if not path.is_file():
            errs.append(f"missing document {path.name}")
            continue
        rendered, problems_here = render(path, recs, total)
        errs.extend(problems_here)
        if not problems_here and rendered != path.read_text(encoding="utf-8"):
            errs.append(f"{path.name}: generated block drift - run "
                        f"`python3 scripts/aimf_question_bank.py generate`")

    # the generated document must carry one row per catalog control, and no
    # other line may begin with a bare control ID - that is the acceptance
    # command a reviewer runs (`grep -c '^| GOV-...</div>'`), so a table that
    # happens to start rows with IDs elsewhere in the document would inflate it.
    rows_in_bank = len(re.findall(r"^\| (?:GOV|MAP|MEA|MAN)-\d+\.\d+ \|", bank_text, re.MULTILINE))
    if rows_in_bank != len(ids):
        errs.append(f"{BANK_MD.name}: {rows_in_bank} lines begin with a control ID, expected {len(ids)} "
                    f"(one row per control and no other table keyed by control ID)")
    if OLD_SCALE_RE.search(bank_text):
        errs.append(f"{BANK_MD.name}: asserts a retired or invented scale")
    if f"{len(recs)}/{total}" not in bank_text:
        errs.append(f"{BANK_MD.name}: coverage statement does not show {len(recs)}/{total}")
    return errs


# ---------------------------------------------------------------------------
def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("mode", choices=["generate", "check", "report"])
    args = ap.parse_args()

    recs, problems = records()
    total = len(am.load_catalog())

    if args.mode == "generate":
        for path in BLOCKS:
            rendered, problems_here = render(path, recs, total)
            for p in problems_here:
                print("  !!", p)
            path.write_text(rendered, encoding="utf-8")
            print(f"  rendered {path.name}")
        errs = validate(recs, total, problems)
        for e in errs:
            print("  !!", e)
        return 1 if errs else 0

    if args.mode == "report":
        by_audience = OrderedDict((a, sum(1 for r in recs if r["audience"] == a)) for a in AUDIENCE_ORDER)
        anchors = len(recs) * len(ANCHORS)
        print(f"controls: {total}")
        print(f"bank rows: {len(recs)}")
        print(f"audiences: " + ", ".join(f"{a} {n}" for a, n in by_audience.items()))
        print(f"anchors: {anchors} ({len(recs)} controls x {len(ANCHORS)} levels)")
        print(f"roles: {len({r['role'] for r in recs})} distinct")
        return 0

    errs = validate(recs, total, problems)
    if errs:
        for e in errs:
            print("FAIL:", e)
        return 1
    print(f"OK: question bank covers {len(recs)}/{total} controls with "
          f"{len(ANCHORS)} anchors each and no drift")
    return 0


if __name__ == "__main__":
    sys.exit(main())
