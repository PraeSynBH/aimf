#!/usr/bin/env python3
"""AIMF standards-mapping generator and drift validator.

Single source of truth
----------------------
* ``core/AIMF-CONTROL-CATALOG.csv`` - resolved relative to this script's own
  packaged directory, i.e. ``documents/AIMF-Full-Documentation/`` in the source
  repository - supplies the NIST AI RMF subcategory, ISO 42001 clause and
  capability-dimension attribution for all 72 AIMF controls.
* This script supplies the ISO/IEC 27001:2022 Annex A attribution (see
  ``ISO27001_2022`` below), because the catalog's original column mixed the 2013
  and 2022 numbering vintages and left 38 controls untagged.

Generated regions
-----------------
Every mapping document carries machine-rendered tables between markers::

    <!-- BEGIN GENERATED:<block-id> -->
    ...
    <!-- END GENERATED:<block-id> -->

``generate`` rewrites those regions from the data above.  ``check`` re-renders
them in memory and fails (exit 1) if the file on disk has drifted, if a
placeholder/unchecked task is present, if a referenced control id is missing
from the catalog, or if an ISO 27001 reference uses pre-2022 numbering.

It also validates the assessment question bank in
``implementation/AIMF-ASSESSMENT-GUIDE.md``: every catalog control must have
exactly one question row (and one evidence expectation) and the bank must not
carry an id that is absent from the catalog, so the instrument cannot silently
fall back to partial coverage.  Since v1.0.6 it additionally delegates to
``aimf_question_bank.validate``, which checks the generated instrument
(``implementation/AIMF-ASSESSMENT-QUESTION-BANK.md``): one row per control with
a role and five behavioural anchors, the anchor ladder intact, the derived
audience and coverage counts matching the catalog, and no generated-region
drift between the bank and this guide.

Usage
-----
This script ships inside the distribution bundle, so it runs from an unpacked
bundle root (or from the repository copy of the packaged directory)::

    python3 scripts/aimf_mappings.py generate   # rewrite CSV column + doc blocks
    python3 scripts/aimf_mappings.py check      # validate only (exit 1 on drift)

The packaged directory that contains this script is auto-detected, so the same
file works in the repository and in an unpacked bundle.  The repository-root
``scripts/aimf_mappings.py`` is a thin shim that delegates here.
"""

