CATALOG_MD = DOCS / "core" / "AIMF-CONTROL-CATALOG.md"
CATALOG_MD_CTRL_RE = re.compile(r"^### ((?:GOV|MAP|MEA|MAN)-\d+\.\d+):")
CATALOG_MD_META_RE = re.compile(r"^\*\*ISO 42001\*\*:.*$")


def render_catalog_md_line(row: dict) -> str:
    clauses = ", ".join(split_refs(row["ISO42001_Clauses"]))
    iso27 = row["ISO27001_Controls"].strip() or NO_ANALOGUE
    return f"**ISO 42001**: {clauses} | **ISO 27001**: {iso27}"


def normalize_catalog_md(rows: list[dict]) -> tuple[str, list[str]]:
    """Rewrite the standards metadata line of every control section of the
    human-readable catalog so it agrees with the CSV the generator owns."""
    by_id = {r["Control_ID"]: r for r in rows}
    text = CATALOG_MD.read_text(encoding="utf-8")
    out, current, seen, problems = [], None, set(), []
    for line in text.split("\n"):
        m = CATALOG_MD_CTRL_RE.match(line)
        if m:
            if current is not None and current not in seen:
                problems.append(f"catalog md: control {current} has no standards metadata line")
            current = m.group(1)
            seen.add(current)
            out.append(line)
            continue
        if line.startswith("### ") and current is not None:
            if current not in seen:
                problems.append(f"catalog md: control {current} has no standards metadata line")
            current = None
            out.append(line)
            continue
        if current is not None and CATALOG_MD_META_RE.match(line):
            out.append(render_catalog_md_line(by_id[current]))
            continue
        out.append(line)
    if current is not None and current not in seen:
        problems.append(f"catalog md: control {current} has no standards metadata line")
    for cid in by_id:
        if cid not in seen:
            problems.append(f"catalog md: control {cid} section missing from the catalog")
    return "\n".join(out), problems


