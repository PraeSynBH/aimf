def render_doc(path: Path, rows: list[dict]) -> tuple[str, list[str]]:
    text = path.read_text(encoding="utf-8")
    problems = []
    for block_id, fn in BLOCKS[path.name].items():
        # The replacement deliberately swallows the provenance note line that
        # precedes the BEGIN marker, when it is already there.  Without that,
        # every pass prepends a fresh note and `check` reports drift immediately
        # after `generate`.
        body = block_replacement(block_id, fn(rows))
        pattern = block_pattern(block_id)
        if not pattern.search(text):
            problems.append(f"{path.name}: missing generated block '{block_id}'")
            continue
        text = pattern.sub(lambda _m, b=body: b, text)
    return text, problems


# ---------------------------------------------------------------------------
# validation
# ---------------------------------------------------------------------------
PLACEHOLDER_RE = re.compile(r"Required Research|detailed mapping required", re.IGNORECASE)
UNCHECKED_RE = re.compile(r"^\s*-\s*\[ \]", re.MULTILINE)
CONTROL_RE = re.compile(r"\b(?:GOV|MAP|MEA|MAN)-\d+\.\d+\b")
ISO27001_REF_RE = re.compile(r"\bA\.\d+\.\d+\b")
OLD_VINTAGE_RE = re.compile(r"\bA\.(?:9|18)\.\d+\b")
NIST_REF_RE = re.compile(r"\b(?:GOVERN|MAP|MEASURE|MANAGE) \d+\.\d+\b")
STATUS_RE = re.compile(r"^\*\*Status\*\*:", re.MULTILINE)
STATUS_FORBIDDEN_RE = re.compile(
    r"research required|research needed|detailed mapping required|\bTBD\b|working draft",
    re.IGNORECASE)


def validate(rows: list[dict], check_files: bool = True) -> list[str]:
    errs = []
    ids = {r["Control_ID"] for r in rows}

    # 1. catalog ISO 27001 column matches the script table
    for r in rows:
        want = ", ".join(ISO27001_2022[r["Control_ID"]])
        if r["ISO27001_Controls"].strip() != want:
            errs.append(f"catalog drift: {r['Control_ID']} ISO27001_Controls="
                        f"{r['ISO27001_Controls']!r} expected {want!r}")
    missing = ids - set(ISO27001_2022)
    if missing:
        errs.append(f"controls absent from ISO27001_2022 table: {sorted(missing)}")

    # 2. NIST completeness
    refs = sorted({r["NIST_RMF_Subcategory"].strip() for r in rows}, key=nist_sort_key)
    if len(refs) != 72:
        errs.append(f"NIST subcategory coverage is {len(refs)}, expected 72")

    if not check_files:
        return errs

    # 3. per-document checks
    header_status = {}
    for path in sorted(MAPPINGS.glob("*.md")):
        text = path.read_text(encoding="utf-8")
        # The vintage-normalisation table deliberately quotes retired 2013
        # reference numbers; exclude it from the 2022-only rule below.
        scan_text = re.sub(
            re.escape(BEGIN.format("iso27001-vintage")) + r".*?" + re.escape(END.format("iso27001-vintage")),
            "", text, flags=re.DOTALL)
        for m in PLACEHOLDER_RE.finditer(text):
            errs.append(f"{path.name}: placeholder text {m.group(0)!r}")
        for m in UNCHECKED_RE.finditer(text):
            errs.append(f"{path.name}: unchecked task at offset {m.start()}")
        for cid in sorted(set(CONTROL_RE.findall(text))):
            if cid not in ids:
                errs.append(f"{path.name}: unknown control id {cid}")
        for ref in sorted(set(ISO27001_REF_RE.findall(scan_text))):
            if OLD_VINTAGE_RE.match(ref):
                errs.append(f"{path.name}: pre-2022 ISO 27001 reference {ref}")
        head = text.split("\n---", 1)[0]
        statuses = STATUS_RE.findall(head)
        if len(statuses) != 1:
            errs.append(f"{path.name}: expected exactly one header **Status** line, found {len(statuses)}")
        else:
            m = re.search(r"^\*\*Status\*\*:\s*(.+)$", head, re.MULTILINE)
            status = m.group(1).strip() if m else ""
            header_status[path.name] = status
            if STATUS_FORBIDDEN_RE.search(status):
                errs.append(f"{path.name}: header status is a placeholder ({status!r})")

    # 4. generated blocks match
    for name in BLOCKS:
        path = MAPPINGS / name
        if not path.exists():
            errs.append(f"missing mapping document {name}")
            continue
        rendered, problems = render_doc(path, rows)
        errs.extend(problems)
        if not problems and rendered != path.read_text(encoding="utf-8"):
            errs.append(f"{name}: generated block drift - run `python3 scripts/aimf_mappings.py generate`")

    # 4b. human-readable catalog agrees with the CSV
    md_text, md_problems = normalize_catalog_md(rows)
    errs.extend(md_problems)
    if not md_problems and md_text != CATALOG_MD.read_text(encoding="utf-8"):
        errs.append("core/AIMF-CONTROL-CATALOG.md: standards metadata drift - run "
                    "`python3 scripts/aimf_mappings.py generate`")

    # 4c. the assessment question bank covers the catalog exactly
    bank_text = QUESTION_BANK_MD.read_text(encoding="utf-8")
    errs.extend(validate_question_bank(rows, bank_text))

    # 4d. the generated instrument: anchors, roles, derived audiences, coverage
    #     counts.  Rendered from the catalog plus the authored bank source, so
    #     a bank edit cannot ship with the tables, counts or anchors out of step.
    try:
        import aimf_question_bank as question_bank
    except ImportError:
        errs.append("scripts/aimf_question_bank.py is missing - the assessment "
                    "question bank cannot be validated")
    else:
        bank_records, bank_problems = question_bank.records()
        errs.extend(question_bank.validate(bank_records, len(rows), bank_problems))

    # 5. NIST document carries all 72 subcategory ids
    nist_doc = (MAPPINGS / "AIMF-NIST-RMF-MAPPING.md").read_text(encoding="utf-8")
    found = sorted(set(NIST_REF_RE.findall(nist_doc)), key=nist_sort_key)
    if found != refs:
        errs.append(f"AIMF-NIST-RMF-MAPPING.md: {len(found)} unique subcategory references, expected 72")

    # 6. ISO 42001 clause references used in the document exist in the catalog
    catalog_clauses = {c for r in rows for c in split_refs(r["ISO42001_Clauses"])}
    iso42001_doc = (MAPPINGS / "AIMF-ISO42001-MAPPING.md").read_text(encoding="utf-8")
    for clause in sorted(set(re.findall(r"^\| (\d+(?:\.\d+)*) \|", iso42001_doc, re.MULTILINE))):
        if clause not in ISO42001_HEADINGS:
            errs.append(f"AIMF-ISO42001-MAPPING.md: clause {clause} is not an ISO/IEC 42001 heading")
    if not catalog_clauses <= set(ISO42001_HEADINGS):
        errs.append(f"catalog clause refs not in ISO/IEC 42001 headings: "
                    f"{sorted(catalog_clauses - set(ISO42001_HEADINGS))}")

    # 7. EO 14179 controls exist
    eo_doc = (MAPPINGS / "AIMF-EXECUTIVE-ORDER-14179-MAPPING.md").read_text(encoding="utf-8")
    for cid in sorted(set(CONTROL_RE.findall(eo_doc))):
        if cid not in ids:
            errs.append(f"AIMF-EXECUTIVE-ORDER-14179-MAPPING.md: unknown control id {cid}")
    if len(EO14179_ACTIONS) < 10:
        errs.append("EO 14179 action table is unexpectedly short")
    for _title, (_desc, ctrls) in EO14179_ACTIONS.items():
        for cid in ctrls:
            if cid not in ids:
                errs.append(f"EO14179_ACTIONS references unknown control {cid}")

    return errs


