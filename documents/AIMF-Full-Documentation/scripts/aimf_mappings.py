def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("mode", choices=["generate", "check", "report"])
    args = ap.parse_args()

    rows = load_catalog()
    if args.mode == "generate":
        apply_iso27001(rows)
        write_catalog(rows)
        print(f"catalog updated: {CATALOG_CSV.relative_to(REPO)}")
        md_text, md_problems = normalize_catalog_md(rows)
        for p in md_problems:
            print("  !!", p)
        if not md_problems and md_text != CATALOG_MD.read_text(encoding="utf-8"):
            CATALOG_MD.write_text(md_text, encoding="utf-8")
            print(f"catalog updated: {CATALOG_MD.relative_to(REPO)}")
        for name in BLOCKS:
            path = MAPPINGS / name
            rendered, problems = render_doc(path, rows)
            for p in problems:
                print("  !!", p)
            path.write_text(rendered, encoding="utf-8")
            print(f"  rendered {name}")
        errs = validate(rows)
        for e in errs:
            print("  !!", e)
        return 1 if errs else 0

    if args.mode == "report":
        tagged = sum(1 for r in rows if ISO27001_2022[r["Control_ID"]][0] != NO_ANALOGUE)
        print(f"controls: {len(rows)}")
        print(f"ISO 27001:2022 tagged: {tagged}, reviewed-no-analogue: {len(rows) - tagged}")
        print(f"NIST subcategories: {len({r['NIST_RMF_Subcategory'] for r in rows})}")
        print(f"ISO 42001 clauses: {len({c for r in rows for c in split_refs(r['ISO42001_Clauses'])})}")
        bank, _ = parse_question_bank(QUESTION_BANK_MD.read_text(encoding="utf-8"))
        print(f"question bank: {len(bank)} of {len(rows)} controls have a question")
        return 0

    errs = validate(rows)
    if errs:
        for e in errs:
            print("FAIL:", e)
        return 1
    print("OK: mapping documents, catalog and generated tables are consistent")
    return 0


if __name__ == "__main__":
    sys.exit(main())
