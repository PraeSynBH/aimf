def load_catalog() -> list[dict]:
    with CATALOG_CSV.open(newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def cell(value: str) -> str:
    return " ".join(value.replace("|", "\\|").split())


def md_table(headers: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    for row in rows:
        out.append("| " + " | ".join(cell(c) for c in row) + " |")
    return "\n".join(out)


def split_refs(value: str) -> list[str]:
    return [p.strip() for p in value.split(",") if p.strip()]


def nist_sort_key(ref: str):
    fn, num = ref.split(" ", 1)
    order = {"GOVERN": 0, "MAP": 1, "MEASURE": 2, "MANAGE": 3}
    major, minor = (num.split(".") + ["0"])[:2]
    return (order.get(fn, 9), int(major), int(minor))


def wrap(block_id: str, body: str) -> str:
    return "\n".join([BEGIN.format(block_id), body.rstrip(), END.format(block_id)])


def block_pattern(block_id: str) -> "re.Pattern[str]":
    """Match a generated region, tolerating the generator note above the marker."""
    return re.compile(
        r"(?:<!-- GENERATED by [^\n]*-->\n)?"
        + re.escape(BEGIN.format(block_id)) + r".*?" + re.escape(END.format(block_id)),
        re.DOTALL)


def block_replacement(block_id: str, body: str) -> str:
    return GEN_NOTE + "\n" + wrap(block_id, body)


